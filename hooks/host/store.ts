import type { EngineInterface } from 'claude-code'

import { initial, replay } from '../engine/engine'
import { skillState } from '../engine/mastery'
import { stats, statsText, weaknessText } from '../engine/stats'
import type { Course, LearnerState, LogEvent, Segment } from '../engine/types'
import { validateCourse, validateSegment } from '../engine/schema'

export const DIR = '.teachme'

export type Loaded = { course?: Course; segments: Record<string, Segment>; state: LearnerState; errors: string[] }

async function readJson($: EngineInterface, path: string) {
  return JSON.parse(await $.fs.read(path))
}

export async function hasCourse($: EngineInterface, root: string) {
  return $.fs.exists(`${root}/${DIR}/course.json`)
}

export async function load($: EngineInterface, root: string): Promise<Loaded> {
  const errors: string[] = []
  let course: Course | undefined
  try {
    const c = await readJson($, `${root}/${DIR}/course.json`)
    const bad = validateCourse(c)
    if (bad.length) errors.push(...bad.map(e => `course.json: ${e}`)); else course = c
  } catch (err) {
    errors.push(`course.json: ${err}`)
  }
  const segments: Record<string, Segment> = {}
  for (const f of await $.fs.list(`${root}/${DIR}/scripts`).catch(() => [])) {
    if (f.kind !== 'file' || !f.name.endsWith('.json')) continue
    try {
      const g = await readJson($, `${root}/${DIR}/scripts/${f.name}`)
      const bad = validateSegment(g, course)
      if (bad.length) errors.push(...bad.map(e => `${f.name}: ${e}`)); else segments[g.id] = g
    } catch (err) {
      errors.push(`${f.name}: ${err}`)
    }
  }
  return { course, segments, state: replay(await readLogs($, root)), errors }
}

export async function readLogs($: EngineInterface, root: string): Promise<LogEvent[]> {
  const all: LogEvent[] = []
  for (const f of await $.fs.list(`${root}/${DIR}/log`).catch(() => [])) {
    if (f.kind !== 'file' || !f.name.endsWith('.jsonl')) continue
    const text = await $.fs.read(`${root}/${DIR}/log/${f.name}`).catch(() => '')
    for (const line of text.split('\n')) {
      if (!line.trim()) continue
      try { all.push(JSON.parse(line)) } catch { }
    }
  }
  return all.map((e, i) => ({ e, i })).sort((a, b) => a.e.ts - b.e.ts || a.i - b.i).map(x => x.e)
}

export type Log = { path: string; device: string; lines?: string[]; chain: Promise<void> }

export const newLog = (root: string, device: string, name = `log/${device}-${new Date().toISOString().slice(0, 7)}`): Log => ({ path: `${root}/${DIR}/${name}.jsonl`, device, chain: Promise.resolve() })

export function append($: EngineInterface, log: Log, events: readonly object[]) {
  if (!events.length) return log.chain
  log.chain = log.chain.then(async () => {
    log.lines ??= (await $.fs.read(log.path).catch(() => '')).split('\n').filter(l => l.trim())
    log.lines.push(...events.map(e => JSON.stringify({ ...e, device: log.device })))
    await $.fs.write(log.path, log.lines.join('\n') + '\n')
  }).catch(err => $.ui.log(`teachme: log write failed: ${err}`, { to: 'debug' }))
  return log.chain
}

export async function install($: EngineInterface, root: string, course: Course, segments: readonly Segment[]) {
  await $.fs.write(`${root}/${DIR}/course.json`, JSON.stringify(course, null, 2) + '\n')
  for (const g of segments) await $.fs.write(`${root}/${DIR}/scripts/${g.id}.json`, JSON.stringify(g, null, 2) + '\n')
  await $.fs.write(`${root}/${DIR}/.gitignore`, 'env.json\nmetrics.jsonl\nstaging/\n')
  await $.fs.write(`${root}/${DIR}/.gitattributes`, 'log/*.jsonl merge=union\n')
}

export function progressMarkdown(course: Course, s: LearnerState, now: number): string {
  const rows = course.skills.map(k => `| \`${k.id}\` | ${k.title} | ${skillState(s, k.id, now)} | ${s.evidence.filter(e => e.skill === k.id && e.ok).length} |`)
  const weak = Object.values(s.weak).filter(w => w.status !== 'resolved').map(w =>
    weaknessText(course, w) + (w.status === 'recheck' && w.due ? ` (re-check from ${new Date(w.due).toISOString().slice(0, 10)})` : ''))
  return [
    `# Progress: ${course.subject}`, '',
    '<!-- Generated by Teach Me from .teachme/log. Edits here are overwritten. -->', '',
    `Stage: ${s.stage}${s.pos ? ` · ${s.pos.seg} step ${s.pos.step + 1}` : ''}`, '',
    '| Skill | | State | Right answers |', '|---|---|---|---|', ...rows, '',
    ...(weak.length ? ['Keep sharp:', ...weak.map(w => `- ${w}`)] : []), '',
    '## Your answers', '', statsText(course, stats(course, s, now)), '',
  ].join('\n')
}

